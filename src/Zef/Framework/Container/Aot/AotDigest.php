<?php

declare(strict_types=1);

namespace Zef\Framework\Container\Aot;

/**
 * The compile/dump lane's configuration fingerprint: a stable digest over
 * the definition-source maps, the one number that decides whether an
 * artifact still describes the configuration it was dumped from.
 *
 * The digest folds the six source maps (the framework's own
 * registrations, the host's declarations, the parameters, the
 * autoconfiguration rules, the contextual bindings and the decoration
 * chains) plus the framework
 * version into a SHA-256 over a canonical type-tagged walk. The walk is
 * deliberate about the three things a naive serialisation gets wrong:
 *
 * - **Types are named**: `1` (int), `'1'` (string), `1.0` (float) and
 *   `true` fold differently, so a value's type is part of its spelling.
 * - **Key order is part of the fingerprint**: the maps are handed over in
 *   one fixed order by the one caller that builds them, and a
 *   reordered-but-equivalent configuration is a different spelling the
 *   digest conservatively refuses to equate.
 * - **Only data folds**: an object, closure or resource anywhere in the
 *   input refuses the digest ({@see AotRefusals::notDigestible()}) --
 *   object identity is not stable across the two processes that must
 *   agree (the dump and the boot), so a configuration the digest cannot
 *   fold is a configuration the artifact cannot honestly carry either.
 *
 * The invalidation contract this digest serves (ROADMAP area 8's
 * "cache invalidation otomatis", read through the repository's KDD-6
 * lens): the artifact is an acceleration, never a source of truth, so
 * the digest decides between exactly three honest answers -- a match
 * loads, an absent artifact compiles and dumps, and a mismatch is
 * *proven* staleness the boot never runs, compiling afresh and laying
 * a fresh artifact down. What the digest does not cover -- a class
 * file edited without a version bump or a rebuild -- stays a
 * build-pipeline concern the way the configuration cache's KDD-6 already
 * frames staleness: explicit tooling, not a runtime guess.
 */
final readonly class AotDigest
{
    /**
     * Folds the source maps and the framework version into one digest.
     *
     * @param array<string, mixed> $sources the six source maps under
     *                                      their own keys, in the one
     *                                      fixed order the caller builds
     * @param string               $version the framework version the dump
     *                                      was generated by
     *
     * @return non-empty-string the SHA-256 fingerprint, always 64 hex
     *                          characters by construction
     */
    public static function over(array $sources, string $version): string
    {
        $folded = '';

        foreach ($sources as $name => $value) {
            $folded .= 'map:' . self::fold($value, $name) . "\n";
        }

        return hash('sha256', $folded . 'version:' . $version);
    }

    /**
     * Folds one value into its canonical type-tagged spelling, refusing
     * what a cross-process fingerprint cannot honestly carry.
     *
     * @param string $path the dotted position, for the refusal
     */
    private static function fold(mixed $value, string $path): string
    {
        return match (true) {
            \is_int($value) => 'int:' . $value,
            \is_string($value) => 'string:' . $value,
            \is_bool($value) => 'bool:' . ($value ? 'true' : 'false'),
            \is_float($value) => 'float:' . var_export($value, true),
            $value === null => 'null',
            \is_array($value) => self::foldEntries($value, $path),
            default => throw AotRefusals::notDigestible($path, $value),
        };
    }

    /**
     * The array arm: each entry folded into its type-tagged spelling,
     * keyed under its own name or position.
     *
     * @param array<mixed> $value the array being folded
     * @param string       $path  the dotted position, for the refusals
     */
    private static function foldEntries(array $value, string $path): string
    {
        $entries = '';

        foreach ($value as $key => $entry) {
            $entries .= (\is_int($key) ? 'idx:' : 'key:') . $key . '='
                . self::fold($entry, $path . '.' . $key) . ';';
        }

        return '[' . $entries . ']';
    }
}

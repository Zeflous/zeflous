<?php

declare(strict_types=1);

namespace Zef\Framework\Container\Aot;

use ParseError;
use Zef\Framework\Container\ContainerCompilePlan;

/**
 * The compiled container cache: the compile/dump lane's fast-path
 * artifact (ROADMAP area 8, the container-side sibling of the
 * configuration layer's own {@see \Zef\Framework\Config\Cache\ConfigCache}).
 *
 * `dump()` writes the artifact -- the planned definition set rendered
 * into a plain PHP file whose array literal carries the live closures
 * ({@see AotEntries}), the baked tag index, the baked unreferenced
 * report and the configuration digest -- and `load()` reads it back
 * with `require`, the cheapest deserialisation PHP itself can do. The
 * write is atomic (a temporary file renamed over the target, the
 * contract a concurrent dumper and a concurrent boot never observe
 * half of), and every load failure is fail-closed with the file named:
 * a missing artifact, a payload that is not a map, a torn or hand-edited
 * file that does not parse at all, and a structurally malformed payload
 * all refuse ({@see AotArtifact}) -- never a silent empty container.
 *
 * The staleness contract is the configuration cache's KDD-6 mirrored
 * and narrowed to what an *acceleration* may honestly do: a present
 * artifact whose digest matches the live configuration is loaded
 * (never rebuilt -- the fast path a persistent worker takes); an
 * absent artifact is compiled and dumped (the first boot that wires
 * the seam lays it down, exactly the configuration cache's own
 * miss-handling); and a present artifact whose digest does not match
 * is *proven* stale, so it is never run -- the boot compiles afresh
 * and lays a fresh artifact down (ROADMAP area 8's automatic
 * invalidation: a deterministic digest over the in-memory
 * configuration, never a filesystem heuristic the runtime guesses
 * at). What the digest does not cover -- a class file edited without
 * a rebuild -- is the build pipeline's concern exactly as KDD-6
 * frames it: explicit tooling, not a runtime guess.
 *
 * @phpstan-import-type ArtifactDumpEntry from AotEntries
 *
 * @psalm-import-type ArtifactDumpEntry from AotEntries
 */
final readonly class ContainerAotCache
{
    private const string GENERATED_HEADER
        = '// Generated by the Zef container AOT cache; never edit it by hand.';

    /**
     * @param string $file path of the cache artifact (written by dump,
     *                     read by load)
     */
    public function __construct(
        private string $file,
    ) {
    }

    /**
     * The artifact's location, as the refusal messages spell it.
     */
    public function file(): string
    {
        return $this->file;
    }

    /**
     * Whether an artifact is present: the lane's existence check, the
     * difference between "cold cache, full compile" and "artifact
     * present, digest decides".
     */
    public function exists(): bool
    {
        return is_file($this->file);
    }

    /**
     * Writes the artifact, replacing whatever the file carried before.
     *
     * @param non-empty-string                 $digest       the configuration fingerprint
     * @param array<string, ArtifactDumpEntry> $entries      the rendered entries
     * @param array<string, list<string>>      $tags         the baked tag index
     * @param list<string>                     $unreferenced the baked unreferenced report
     */
    public function dump(string $digest, array $entries, array $tags, array $unreferenced): void
    {
        $directory = \dirname($this->file);

        if (!is_dir($directory)) {
            throw AotRefusals::cacheDirectoryMissing($this->file);
        }

        $code = "<?php\n\n" . self::GENERATED_HEADER . "\n\nreturn [\n"
            . "    'digest' => " . var_export($digest, true) . ",\n"
            . "    'unreferenced' => " . var_export($unreferenced, true) . ",\n"
            . "    'tags' => " . var_export($tags, true) . ",\n"
            . "    'entries' => [\n"
            . $this->renderedEntries($entries)
            . "    ],\n"
            . "];\n";

        // A PID alone collides when two processes dump the same target
        // concurrently; the random suffix preserves the atomic-rename
        // contract for each individual writer.
        $temporary = $this->file . '.tmp.' . bin2hex(random_bytes(6));

        if (file_put_contents($temporary, $code, \LOCK_EX) === false) {
            throw AotRefusals::artifactUnwritable($this->file);
        }

        if (rename($temporary, $this->file)) {
            return;
        }

        if (is_file($temporary)) {
            unlink($temporary);
        }

        throw AotRefusals::artifactUnfinalisable($this->file);
    }

    /**
     * Dumps a compile plan as the fresh artifact: the planned set's
     * rendered entries, baked tag index and unreferenced report under
     * the source configuration's fingerprint -- the write the full lane
     * leaves behind for the next boot.
     *
     * @param non-empty-string $digest the source configuration's fingerprint
     */
    public function dumpPlan(ContainerCompilePlan $containerCompilePlan, string $digest): void
    {
        $this->dump(
            $digest,
            AotEntries::all($containerCompilePlan->definitions),
            $containerCompilePlan->tagIndex->toArray(),
            $containerCompilePlan->unreferenced,
        );
    }

    /**
     * Loads and validates the artifact.
     *
     * A plain `require`, deliberately not `require_once`: the artifact
     * is a side-effect-free `<?php return [...];` data file, and a
     * second container booted from the same artifact in one process
     * must keep reading the payload (the configuration cache's own
     * envelope rationale).
     */
    public function load(): AotArtifact
    {
        if (!is_file($this->file)) {
            throw AotRefusals::artifactMissing($this->file);
        }

        try {
            $payload = require $this->file;
        } catch (ParseError $parseError) {
            throw AotRefusals::artifactCorrupt($this->file, $parseError->getMessage());
        }

        return AotArtifact::validated($this->file, $payload);
    }

    /**
     * Renders the entries block: closure entries embed their rendered
     * code verbatim (the array literal evaluates it into a live closure
     * at `require` time), build entries export as plain data.
     *
     * @param array<string, array{kind: 'build', factory: string, arguments: list<mixed>,
     *     calls: list<array{method: string, arguments: list<mixed>}>, lifetime: string}
     *     |array{kind: 'closure', closure: string, lifetime: string}> $entries
     */
    private function renderedEntries(array $entries): string
    {
        $rendered = '';

        foreach ($entries as $id => $entry) {
            if ($entry['kind'] === 'closure') {
                $rendered .= '        ' . var_export($id, true) . " => [\n"
                    . "            'kind' => 'closure',\n"
                    . '            ' . "'closure' => " . $entry['closure'] . ",\n"
                    . '            ' . "'lifetime' => " . var_export($entry['lifetime'], true) . ",\n"
                    . "        ],\n";
            } else {
                $rendered .= '        ' . var_export($id, true) . ' => ' . var_export($entry, true) . ",\n";
            }
        }

        return $rendered;
    }
}

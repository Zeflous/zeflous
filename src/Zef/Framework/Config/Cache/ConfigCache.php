<?php

declare(strict_types=1);

namespace Zef\Framework\Config\Cache;

use ParseError;
use Throwable;
use Zef\Framework\Config\ConfigException;

/**
 * The compiled configuration cache: the fast-path artifact of the
 * configuration layer (see `ROADMAP.md`, "Configuration System + DSL +
 * Radix Tree" -- "Jika ada cache, baca dari cache").
 *
 * `dump()` compiles a configuration array into a plain PHP file that
 * `load()` executes back into the same array -- `var_export()` output
 * behind a `return`, the cheapest deserialisation PHP itself can do, with
 * zero dependencies and no format to version. The round trip is the
 * identity: nested maps, lists, `null`, booleans, integers, floats and
 * unicode strings survive byte-for-byte (pinned by test). The data
 * language is the configuration layer's own -- arrays and scalars, exactly
 * what the loaders, the layered merger and the environment fold produce;
 * a value that `var_export()` cannot express as such (an object, a
 * closure) is outside the contract by construction.
 *
 * The cache is deterministic and **mtime-free** (the KDD-6 decision): the
 * load path never stats the source files to decide freshness, because a
 * persistent worker loads once per process, not once per request, and a
 * rebuild is an explicit tooling act (`dump()` again), never a heuristic
 * the runtime guesses at. Consequence, deliberate: a cache written
 * alongside its sources by the rebuild tooling is trusted until the next
 * rebuild; staleness is a build-pipeline concern, not a runtime one.
 *
 * Every failure is fail-closed with the offending path in the message: a
 * `dump()` whose target directory does not exist, a write that fails, a
 * `load()` of a missing cache, a cache that does not return an array, or a
 * cache file that is not valid PHP at all (a torn write, a hand edit, a
 * truncated file) all throw a {@see ConfigException} -- never a silent
 * empty configuration. The "not valid PHP" shape is the one a partial
 * write actually produces: `require` then raises a
 * {@see ParseError} while parsing, which `load()` catches and re-throws as
 * a {@see ConfigException}, and a cache that parses but *raises* during
 * its own load (a hand edit that calls something) answers the same
 * contract through the broader `Throwable` arm -- the fail-closed
 * contract covers *every* corruption shape and not only those that
 * happen to parse.
 *
 * The write itself is atomic ({@see self::dump()}): the payload lands
 * in a uniquely named sibling first and crosses to the cache's own
 * name through one `rename()`, so concurrent cold boots against one
 * artifact path can never tear the file a reader observes -- a reader
 * sees either the whole previous artifact or the whole new one, and
 * the in-place write a torn cache could once produce is gone (the
 * staging-name doctrine the AOT artifact's own dump keeps).
 *
 * The class is the cache seam the kernel bootstrapper will wire (dump at
 * build time, load at boot), which is why it is marked `@api` rather than
 * being baselined or suppressed.
 *
 * @api
 */
final readonly class ConfigCache
{
    private const string GENERATED_HEADER = '// Generated by the Zef configuration cache; never edit it by hand.';

    /**
     * @param non-empty-string $file path of the cache artifact (created by dump, read by load)
     */
    public function __construct(
        private string $file,
    ) {
    }

    /**
     * Compiles the configuration into the cache file, replacing whatever
     * the file carried before -- atomically: the payload lands in a
     * uniquely named sibling and crosses to the cache's own name through
     * one `rename()`, so a reader never observes a half-written artifact
     * no matter how many cold boots race the same path.
     *
     * @param array<array-key, mixed> $data
     */
    public function dump(array $data): void
    {
        $directory = \dirname($this->file);

        if (!is_dir($directory)) {
            throw new ConfigException(
                \sprintf('The configuration cache directory "%s" does not exist.', $directory),
            );
        }

        $temporary = $this->stagingName();

        if (file_put_contents($temporary, $this->render($data), \LOCK_EX) === false) {
            throw new ConfigException(
                \sprintf('The configuration cache "%s" could not be written.', $this->file),
            );
        }

        if (!rename($temporary, $this->file)) {
            if (is_file($temporary)) {
                unlink($temporary);
            }

            throw new ConfigException(
                \sprintf('The configuration cache "%s" could not be finalised.', $this->file),
            );
        }
    }

    /**
     * Whether a cache artifact is present for this path -- the bootstrapper's
     * fast-path probe: an existing cache is loaded (and never rebuilt),
     * a missing one is built from sources and compiled.
     */
    public function exists(): bool
    {
        return is_file($this->file);
    }

    /**
     * Loads the compiled configuration; the cache must exist and return an
     * array, otherwise the configuration layer failed, not defaulted.
     *
     * @return array<array-key, mixed>
     */
    public function load(): array
    {
        $file = $this->file;

        if (!is_file($file)) {
            throw new ConfigException(
                \sprintf('The configuration cache "%s" does not exist.', $file),
            );
        }

        try {
            $payload = require $file;
        } catch (ParseError $parseError) {
            throw new ConfigException(
                \sprintf('The configuration cache "%s" is corrupted: it is not valid PHP.', $file),
                0,
                $parseError,
            );
        } catch (Throwable $throwable) {
            throw new ConfigException(
                \sprintf('The configuration cache "%s" is corrupted: it raised during its own load.', $file),
                0,
                $throwable,
            );
        }

        return $this->asArray($payload, $file);
    }

    /**
     * The staging sibling's name: the cache's own basename, the writing
     * process's identity, and entropy enough that two concurrent writers
     * never collide on one staging file -- each rename stays atomic for
     * its own payload.
     *
     * @return non-empty-string the staging path, beside the artifact it feeds
     */
    private function stagingName(): string
    {
        $pid = getmypid();

        return \dirname($this->file) . '/' . basename($this->file)
            . '.' . ($pid === false ? '0' : (string) $pid) . '-' . uniqid('', false) . '.staging';
    }

    /**
     * Renders the cache file: a generated-file header followed by the
     * plain `return` of the `var_export()` output, so the artifact is a
     * valid, diffable PHP file rather than an opaque blob.
     *
     * @param array<array-key, mixed> $data
     */
    private function render(array $data): string
    {
        return '<?php' . "\n\n" . self::GENERATED_HEADER . "\n\nreturn "
            . var_export($data, true) . ";\n";
    }

    /**
     * Narrows the executed cache file's return value to the configuration
     * array; anything else is corruption.
     *
     * @return array<array-key, mixed>
     */
    private function asArray(mixed $value, string $file): array
    {
        if (!\is_array($value)) {
            throw new ConfigException(
                \sprintf('The configuration cache "%s" is corrupted: it does not return an array.', $file),
            );
        }

        return $value;
    }
}

<?php

declare(strict_types=1);

namespace Zef\Framework\Config\Routing;

/**
 * The dump side of the compiled route tree cache ({@see RouteTreeCache}):
 * one question -- what plain data does the compiled tree export as?
 *
 * The artifact's node graph is a plain-data mirror of the built tree:
 * every node exports as `['prefix' => string, 'static' => list<node>,
 * 'parameter' => node|null, 'routes' => list<int>]`, where the integers
 * index into the carried route table and the static children are stored
 * as a LIST because their first-character keys are derived on
 * rehydration, never stored (KDD-RC4 in
 * `docs/ci-notes/router-compiled-cache.md`). The whole artifact is
 * `var_export()` output behind a `return` with a generated-file header --
 * the `ConfigCache` design language: a valid, diffable PHP file rather
 * than an opaque blob, the cheapest deserialisation PHP itself can do.
 *
 * @internal
 */
final class RouteTreeCacheExport
{
    private const string GENERATED_HEADER = '// Generated by the Zef route tree cache; never edit it by hand.';

    /**
     * Renders the cache artifact's full content: the generated-file
     * header, then the plain `return` of the signature, the raw route
     * table and the exported node graph.
     *
     * @param array<mixed>        $routes         the route table in declaration order
     * @param list<CompiledRoute> $compiledRoutes the compiled routes, indexed as the table orders them
     * @param RadixNode           $radixNode      the built tree's root
     */
    public function content(array $routes, array $compiledRoutes, RadixNode $radixNode): string
    {
        $routeIds = [];

        foreach ($compiledRoutes as $index => $compiledRoute) {
            $routeIds[spl_object_id($compiledRoute)] = $index;
        }

        return '<?php' . "\n\n" . self::GENERATED_HEADER . "\n\nreturn "
            . var_export(
                [
                    'signature' => self::signatureOf($routes),
                    'routes' => $routes,
                    'root' => $this->node($radixNode, $routeIds),
                ],
                true,
            ) . ";\n";
    }

    /**
     * The signature of a route table -- the revision identity the
     * artifact records: a deterministic sha256 over the table's plain
     * export, so the same declaration list always carries the same
     * signature and any change to it does not.
     *
     * @param array<mixed> $routes a list of Standard Route Schema entries
     *
     * @return non-empty-string
     */
    public static function signatureOf(array $routes): string
    {
        return hash('sha256', var_export($routes, true));
    }

    /**
     * Exports one node of the compiled graph: the static text it consumes,
     * its static children as a list (the first-character keys are derived
     * on rehydration), its anonymous parameter edge, and the indices of
     * the routes that settle on it, in registration order.
     *
     * @param array<int, int> $routeIds the entry index of every compiled route, by object identity
     *
     * @return array<string, mixed> the exported node
     */
    private function node(RadixNode $radixNode, array $routeIds): array
    {
        $staticChildren = [];

        foreach ($radixNode->staticChildren() as $staticChild) {
            $staticChildren[] = $this->node($staticChild, $routeIds);
        }

        $parameterChild = $radixNode->parameterChild();

        $routeReferences = [];

        foreach ($radixNode->routes() as $compiledRoute) {
            $routeReferences[] = $routeIds[spl_object_id($compiledRoute)];
        }

        return [
            'prefix' => $radixNode->prefix(),
            'static' => $staticChildren,
            'parameter' => $parameterChild instanceof RadixNode
                ? $this->node($parameterChild, $routeIds)
                : null,
            'routes' => $routeReferences,
        ];
    }
}

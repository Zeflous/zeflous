<?php

declare(strict_types=1);

namespace Zef\Framework\Config\Routing;

use ParseError;
use Zef\Framework\Config\ConfigException;

/**
 * The compiled route tree cache: the engine's fast-boot artifact (see
 * `ROADMAP.md`, Router -- "Performance & Production" -- "Compiled Cache
 * File: Ekspor struktur pohon sebagai file PHP statis untuk booting instan
 * di produksi").
 *
 * `dump()` compiles a route table through the engine's own front doors --
 * one `CompiledRoute::fromArray()` per entry, then `RouteTreeBuilder` and
 * the `RadixTree` constructor, exactly the orchestration of
 * `RadixTree::compile()` -- because the export needs the entry-to-route
 * identity map alongside the built tree; the round-trip tests pin the
 * dumped-and-loaded tree against `RadixTree::compile()` so the two
 * orchestrations cannot drift apart. `load()` then rehydrates the tree
 * WITHOUT paying the build again: the radix compression (the node splits
 * and merges that dominate compile time) is never re-run, only replayed
 * from plain data.
 *
 * The artifact is a plain PHP file -- `var_export()` output behind a
 * `return`, the cheapest deserialisation PHP itself can do, with zero
 * dependencies and no format to version (the `ConfigCache` design). It
 * carries three fields:
 *
 * - `signature` -- the sha256 of the route table it was dumped from, the
 *   revision identity below;
 * - `routes` -- the raw Standard Route Schema entries in declaration
 *   order, the data `CompiledRoute::fromArray()` re-validates on load;
 * - `root` -- the node graph: every node is
 *   `['prefix' => string, 'static' => list<node>, 'parameter' => node|null,
 *   'routes' => list<int>]`, where the integers index into `routes` and the
 *   static children are stored as a LIST because their first-character
 *   keys are derived on rehydration, never stored. The root node and every
 *   parameter node carry an empty prefix; a static child never does (its
 *   first character keys it under its parent).
 *
 * The trust boundary follows the configuration cache's KDD-6 decision:
 * mtime-free, and a rebuild is an explicit tooling act (`dump()` again),
 * never a heuristic the runtime guesses at. `load()` therefore replays
 * what is cheap and judges what could be corrupted -- every entry goes
 * through `CompiledRoute::fromArray()` (the same fail-closed net), and the
 * `RouteTableRegistry` re-runs (method claims, host claims and name
 * uniqueness), so a hand-edited artifact that introduces an ambiguous
 * table is refused with the engine's own messages -- while the node graph
 * itself is trusted exactly as far as its shape narrowing sees: a torn
 * write (a `ParseError`), a truncated or non-array artifact, a node that
 * is not the cache's format, a route reference that names no carried
 * entry, or two static children under one first character all fail closed
 * with the artifact path in the message.
 *
 * The signature is the roadmap's "Revision-Aware Compile" as a tooling
 * concern: the runtime NEVER compares it (that would read the sources the
 * cache exists to skip), the rebuild tooling does -- compute
 * `signatureOf()` over the freshly loaded route table, compare it with
 * `signature()`, and re-dump on a mismatch. The recorded signature is not
 * a checksum of the artifact's own content: editing it does not corrupt
 * the artifact, it only changes what the rebuild tooling sees.
 *
 * @api
 */
final readonly class RouteTreeCache
{
    private const string GENERATED_HEADER = '// Generated by the Zef route tree cache; never edit it by hand.';

    private const array ARTIFACT_FIELDS = [
        'signature' => true,
        'routes' => true,
        'root' => true,
    ];

    private const array NODE_FIELDS = [
        'prefix' => true,
        'static' => true,
        'parameter' => true,
        'routes' => true,
    ];

    /**
     * @param non-empty-string $file path of the cache artifact (created by dump, read by load)
     */
    public function __construct(
        private string $file,
    ) {
    }

    /**
     * Compiles the route table and writes the cache artifact, replacing
     * whatever the file carried before, and returns the compiled tree so
     * the build tooling keeps answering from the compilation it just paid
     * for.
     *
     * @param array<mixed> $routes a list of Standard Route Schema entries
     *
     * @throws ConfigException when the table is not a list, an entry is
     *                         invalid, the artifact directory does not
     *                         exist, or the artifact cannot be written
     */
    public function dump(array $routes): RadixTree
    {
        if (!array_is_list($routes)) {
            throw new ConfigException('The route table must be a list of route entries.');
        }

        $compiledRoutes = [];

        foreach (array_keys($routes) as $index) {
            $compiledRoutes[] = CompiledRoute::fromArray($routes[$index]);
        }

        $routeTreeBuilder = new RouteTreeBuilder();
        $radixNode = $routeTreeBuilder->build($compiledRoutes);
        $radixTree = new RadixTree($radixNode, $routeTreeBuilder->registry()->namedRoutes());

        $routeIds = [];

        foreach ($compiledRoutes as $index => $compiledRoute) {
            $routeIds[spl_object_id($compiledRoute)] = $index;
        }

        $directory = \dirname($this->file);

        if (!is_dir($directory)) {
            throw new ConfigException(
                \sprintf('The route tree cache directory "%s" does not exist.', $directory),
            );
        }

        $bytes = file_put_contents($this->file, $this->render($routes, $radixNode, $routeIds));

        if (!\is_int($bytes)) {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" could not be written.', $this->file),
            );
        }

        return $radixTree;
    }

    /**
     * Whether a cache artifact is present for this path -- the boot
     * pipeline's fast-path probe: an existing cache is loaded (and never
     * rebuilt), a missing one is compiled and dumped by the build tooling.
     */
    public function exists(): bool
    {
        return is_file($this->file);
    }

    /**
     * Rehydrates the compiled radix tree from the cache artifact: the
     * entries are re-validated, the registry re-runs, and the node graph
     * is replayed -- the tree build itself is never paid again.
     *
     * @throws ConfigException when the artifact is missing, is not valid
     *                         PHP, does not return the cache format, or
     *                         carries a corrupted table or node graph
     */
    public function load(): RadixTree
    {
        $artifact = $this->artifact();

        $compiledRoutes = [];

        foreach (array_keys($artifact['routes']) as $index) {
            $compiledRoutes[] = CompiledRoute::fromArray($artifact['routes'][$index]);
        }

        $routeTableRegistry = new RouteTableRegistry();

        foreach ($compiledRoutes as $compiledRoute) {
            $routeTableRegistry->register($compiledRoute);
        }

        $rootFields = $this->nodeFields($artifact['root']);
        $radixNode = new RadixNode($rootFields['prefix']);
        $this->hydrateNode($radixNode, $rootFields, $compiledRoutes);

        return new RadixTree($radixNode, $routeTableRegistry->namedRoutes());
    }

    /**
     * The route table signature recorded in the artifact -- the value the
     * rebuild tooling compares `signatureOf()` against to decide whether
     * the routes changed since the last dump. Reading it never touches the
     * sources: it is the artifact's own record.
     *
     * @return non-empty-string
     *
     * @throws ConfigException when the artifact is missing or corrupted
     */
    public function signature(): string
    {
        return $this->artifact()['signature'];
    }

    /**
     * The signature of a route table -- the revision identity `dump()`
     * records: a deterministic sha256 over the table's plain export, so
     * the same declaration list always carries the same signature and any
     * change to it does not.
     *
     * @param array<mixed> $routes a list of Standard Route Schema entries
     *
     * @return non-empty-string
     */
    public static function signatureOf(array $routes): string
    {
        return hash('sha256', var_export($routes, true));
    }

    /**
     * Renders the cache artifact: a generated-file header followed by the
     * plain `return` of the `var_export()` output, so the artifact is a
     * valid, diffable PHP file rather than an opaque blob.
     *
     * @param array<mixed>    $routes   the route table in declaration order
     * @param array<int, int> $routeIds the entry index of every compiled route, by object identity
     */
    private function render(array $routes, RadixNode $radixNode, array $routeIds): string
    {
        return '<?php' . "\n\n" . self::GENERATED_HEADER . "\n\nreturn "
            . var_export(
                [
                    'signature' => self::signatureOf($routes),
                    'routes' => $routes,
                    'root' => $this->exportNode($radixNode, $routeIds),
                ],
                true,
            ) . ";\n";
    }

    /**
     * Exports one node of the compiled graph: the static text it consumes,
     * its static children as a list (the first-character keys are derived
     * on rehydration), its anonymous parameter edge, and the indices of
     * the routes that settle on it, in registration order.
     *
     * @param array<int, int> $routeIds the entry index of every compiled route, by object identity
     *
     * @return array<string, mixed> the exported node
     */
    private function exportNode(RadixNode $radixNode, array $routeIds): array
    {
        $staticChildren = [];

        foreach ($radixNode->staticChildren() as $staticChild) {
            $staticChildren[] = $this->exportNode($staticChild, $routeIds);
        }

        $parameterChild = $radixNode->parameterChild();

        $routeReferences = [];

        foreach ($radixNode->routes() as $compiledRoute) {
            $routeReferences[] = $routeIds[spl_object_id($compiledRoute)];
        }

        return [
            'prefix' => $radixNode->prefix(),
            'static' => $staticChildren,
            'parameter' => $parameterChild instanceof RadixNode
                ? $this->exportNode($parameterChild, $routeIds)
                : null,
            'routes' => $routeReferences,
        ];
    }

    /**
     * Reads the artifact and narrows it to the cache format; every
     * corruption shape the file can take fails closed with the path in
     * the message, including the torn-write shape a partial
     * `file_put_contents()` actually produces (a `require` that raises a
     * `ParseError`).
     *
     * @return array{signature: non-empty-string, routes: list<mixed>, root: mixed}
     */
    private function artifact(): array
    {
        $file = $this->file;

        if (!is_file($file)) {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" does not exist.', $file),
            );
        }

        try {
            $artifact = require $file;
        } catch (ParseError $parseError) {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: it is not valid PHP.', $file),
                0,
                $parseError,
            );
        }

        if (!\is_array($artifact)) {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: it does not return an array.', $file),
            );
        }

        foreach (array_keys($artifact) as $field) {
            if (isset(self::ARTIFACT_FIELDS[$field])) {
                continue;
            }

            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: it carries the unknown field "%s".', $file, $field),
            );
        }

        foreach (array_keys(self::ARTIFACT_FIELDS) as $field) {
            if (\array_key_exists($field, $artifact)) {
                continue;
            }

            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: it does not carry the "%s" field.', $file, $field),
            );
        }

        $signature = $artifact['signature'];

        if (!\is_string($signature) || $signature === '') {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: it does not record a route table signature.', $file),
            );
        }

        $routes = $artifact['routes'];

        if (!\is_array($routes) || !array_is_list($routes)) {
            throw new ConfigException(
                \sprintf('The route tree cache "%s" is corrupted: its route table is not a list.', $file),
            );
        }

        return ['signature' => $signature, 'routes' => $routes, 'root' => $artifact['root']];
    }

    /**
     * Narrows one exported node to the cache's node format: an array of
     * exactly the four node fields, with a string prefix, list static
     * children, a parameter edge that is either a node or absent, and a
     * list of route references.
     *
     * @param mixed $node the exported node
     *
     * @return array{
     *     prefix: string,
     *     static: list<mixed>,
     *     parameter: null|array<mixed>,
     *     routes: list<mixed>,
     * }
     */
    private function nodeFields(mixed $node): array
    {
        if (!\is_array($node)) {
            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node is not an array, got %s.',
                    $this->file,
                    get_debug_type($node),
                ),
            );
        }

        foreach (array_keys($node) as $field) {
            if (isset(self::NODE_FIELDS[$field])) {
                continue;
            }

            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node carries the unknown field "%s".',
                    $this->file,
                    $field,
                ),
            );
        }

        foreach (array_keys(self::NODE_FIELDS) as $field) {
            if (\array_key_exists($field, $node)) {
                continue;
            }

            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node does not carry the "%s" field.',
                    $this->file,
                    $field,
                ),
            );
        }

        if (!\is_string($node['prefix'])) {
            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node prefix is not a string.',
                    $this->file,
                ),
            );
        }

        if (!\is_array($node['static']) || !array_is_list($node['static'])) {
            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node static children are not a list.',
                    $this->file,
                ),
            );
        }

        if ($node['parameter'] !== null && !\is_array($node['parameter'])) {
            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node parameter edge '
                    . 'is neither a node nor absent.',
                    $this->file,
                ),
            );
        }

        if (!\is_array($node['routes']) || !array_is_list($node['routes'])) {
            throw new ConfigException(
                \sprintf(
                    'The route tree cache "%s" is corrupted: a compiled node route references are not a list.',
                    $this->file,
                ),
            );
        }

        return [
            'prefix' => $node['prefix'],
            'static' => $node['static'],
            'parameter' => $node['parameter'],
            'routes' => $node['routes'],
        ];
    }

    /**
     * Rebuilds one node of the graph from its exported fields through the
     * node's own builder mutators: static children are re-keyed under the
     * first character of their prefixes (an empty static prefix, or two
     * children sharing a first character, is corruption the compiled
     * format never contains), the parameter edge is reattached, and the
     * route references are resolved against the re-validated entries,
     * which the artifact indexes exactly as its carried table orders them.
     *
     * @param array{
     *     prefix: string,
     *     static: list<mixed>,
     *     parameter: null|array<mixed>,
     *     routes: list<mixed>,
     * } $nodeFields
     * @param list<CompiledRoute> $compiledRoutes
     */
    private function hydrateNode(RadixNode $radixNode, array $nodeFields, array $compiledRoutes): void
    {
        $claimedFirstCharacters = [];

        foreach (array_keys($nodeFields['static']) as $index) {
            $childFields = $this->nodeFields($nodeFields['static'][$index]);

            if ($childFields['prefix'] === '') {
                throw new ConfigException(
                    \sprintf(
                        'The route tree cache "%s" is corrupted: a compiled node static child carries an empty prefix.',
                        $this->file,
                    ),
                );
            }

            $firstCharacter = mb_substr($childFields['prefix'], 0, 1);

            if (isset($claimedFirstCharacters[$firstCharacter])) {
                throw new ConfigException(
                    \sprintf(
                        'The route tree cache "%s" is corrupted: a compiled node carries two static children '
                        . 'under the first character "%s".',
                        $this->file,
                        $firstCharacter,
                    ),
                );
            }

            $claimedFirstCharacters[$firstCharacter] = $childFields['prefix'];
            $this->hydrateNode($radixNode->appendStaticRun($childFields['prefix']), $childFields, $compiledRoutes);
        }

        if ($nodeFields['parameter'] !== null) {
            $parameterFields = $this->nodeFields($nodeFields['parameter']);
            $parameterRadixNode = new RadixNode($parameterFields['prefix']);
            $radixNode->setParameterChild($parameterRadixNode);
            $this->hydrateNode($parameterRadixNode, $parameterFields, $compiledRoutes);
        }

        foreach ($nodeFields['routes'] as $routeId) {
            if (!\is_int($routeId)) {
                throw new ConfigException(
                    \sprintf(
                        'The route tree cache "%s" is corrupted: a compiled node references a route '
                        . 'by the non-integer "%s".',
                        $this->file,
                        get_debug_type($routeId),
                    ),
                );
            }

            if (!isset($compiledRoutes[$routeId])) {
                throw new ConfigException(
                    \sprintf(
                        'The route tree cache "%s" is corrupted: a compiled node references the route '
                        . 'entry %d the cache does not carry.',
                        $this->file,
                        $routeId,
                    ),
                );
            }

            $radixNode->addRoute($compiledRoutes[$routeId]);
        }
    }
}

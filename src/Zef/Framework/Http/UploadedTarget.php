<?php

declare(strict_types=1);

namespace Zef\Framework\Http;

/**
 * The filesystem lifecycle of an upload move's target: the destination
 * directory is asserted, the temporary sibling is opened exclusively,
 * later renamed onto the caller's final path, and on failure removed
 * again.
 *
 * The engine's fopen() and rename() run through {@see ScopedDiagnostics}
 * -- the capture-style seam -- so each failure message stays
 * byte-identical to the reference implementation (legacy `zef-framework`
 * `Adapters.Http.UploadedFile`) while the engine's diagnostic still
 * reaches the caller instead of the error log.
 */
final class UploadedTarget
{
    /**
     * Asserts that the target's destination directory exists.
     *
     * @param non-empty-string $targetPath
     *
     * @throws HttpException when the destination directory does not exist
     */
    public static function assertDestinationDirectory(string $targetPath): void
    {
        $directory = \dirname($targetPath);
        if (!is_dir($directory)) {
            throw new HttpException("Destination directory does not exist: '{$directory}'.");
        }
    }

    /**
     * Opens the temporary target exclusively.
     *
     * @param non-empty-string $tmpTarget the temporary sibling to create
     *
     * @return resource
     *
     * @throws HttpException when the target cannot be created; the message
     *                       carries the engine's diagnostic when it has one
     */
    public static function open(string $tmpTarget): mixed
    {
        [$dest, $warning] = ScopedDiagnostics::fopen($tmpTarget, 'x+b');
        if ($dest === false) {
            throw new HttpException(
                'Unable to create temporary upload target' . ($warning !== null ? ": {$warning}" : '.'),
            );
        }

        return $dest;
    }

    /**
     * Renames the flushed temporary file onto the caller's final path.
     *
     * @param non-empty-string $tmpTarget
     * @param non-empty-string $targetPath
     *
     * @throws HttpException when the engine rename fails; the message carries
     *                       the final path and the engine's diagnostic
     */
    public static function finalize(string $tmpTarget, string $targetPath): void
    {
        [$renamed, $renameWarning] = ScopedDiagnostics::rename($tmpTarget, $targetPath);
        if (!$renamed) {
            throw new HttpException(
                "Unable to finalize uploaded file to '{$targetPath}'"
                . ($renameWarning !== null ? ": {$renameWarning}" : '.'),
            );
        }
    }

    /**
     * Removes a leftover temporary sibling on the failure path only: the
     * name was generated by the move itself ($targetPath plus a random
     * suffix that never carries request input into a filesystem call), and
     * a cleanup failure must not replace the move failure, which is why
     * the removal is unconditional best effort.
     *
     * @param non-empty-string $tmpTarget
     */
    public static function cleanup(string $tmpTarget): void
    {
        if (!is_file($tmpTarget)) {
            return;
        }

        unlink($tmpTarget);
    }
}

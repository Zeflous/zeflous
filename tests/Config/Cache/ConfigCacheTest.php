<?php

declare(strict_types=1);

namespace Zef\Test\Config\Cache;

use Override;
use ParseError;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use Zef\Framework\Config\Cache\ConfigCache;
use Zef\Framework\Config\ConfigException;

/**
 * @internal
 */
#[CoversClass(ConfigCache::class)]
final class ConfigCacheTest extends TestCase
{
    /** @var non-empty-string */
    private string $directory;

    /** @var non-empty-string */
    private string $file;

    #[Override]
    protected function setUp(): void
    {
        $this->directory = sys_get_temp_dir() . '/zef-cache-' . uniqid('', false);
        mkdir($this->directory);
        $this->file = $this->directory . '/config.cache.php';
    }

    #[Override]
    protected function tearDown(): void
    {
        if (is_file($this->file)) {
            unlink($this->file);
        }

        rmdir($this->directory);
    }

    public function testExistsOnlyAfterADump(): void
    {
        $configCache = new ConfigCache($this->file);

        self::assertFalse($configCache->exists());

        $configCache->dump(['key' => 'value']);

        self::assertTrue($configCache->exists());
    }

    public function testDumpsAGeneratedPhpFileWithTheHeader(): void
    {
        new ConfigCache($this->file)->dump(['debug' => true]);

        $rendered = (string) file_get_contents($this->file);

        self::assertStringStartsWith('<?php', $rendered);
        self::assertStringContainsString(
            '// Generated by the Zef configuration cache; never edit it by hand.',
            $rendered,
        );
        self::assertStringContainsString('return array (', $rendered);
    }

    public function testRoundTripsNestedMapsListsScalarsAndUnicode(): void
    {
        $data = [
            'database' => [
                'host' => 'localhost',
                'port' => 3306,
                'options' => ['persistent' => false, 'timeout' => 2.5],
            ],
            'flags' => ['debug' => true, 'maintenance' => false, 'none' => null],
            'label' => 'café 日本語 🚀',
            'empty_map' => [],
            'empty_list' => [],
        ];

        new ConfigCache($this->file)->dump($data);

        self::assertSame($data, $this->loadDumpedCache());
    }

    public function testRoundTripsAnEmptyConfiguration(): void
    {
        new ConfigCache($this->file)->dump([]);

        self::assertSame([], $this->loadDumpedCache());
    }

    public function testADumpReplacesWhatTheCacheCarriedBefore(): void
    {
        $configCache = new ConfigCache($this->file);
        $configCache->dump(['driver' => 'mysql']);
        $configCache->dump(['driver' => 'postgres']);

        self::assertSame(['driver' => 'postgres'], $this->loadDumpedCache());
    }

    public function testLoadCanBeRepeatedWithinOneProcess(): void
    {
        $configCache = new ConfigCache($this->file);
        $configCache->dump(['retries' => 3]);

        self::assertSame(['retries' => 3], $this->loadDumpedCache());
        self::assertSame(['retries' => 3], $this->loadDumpedCache());
    }

    public function testLoadThrowsWhenTheCacheFileIsMissing(): void
    {
        $configCache = new ConfigCache($this->file);

        try {
            $configCache->load();
            self::fail('A missing configuration cache must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                \sprintf('The configuration cache "%s" does not exist.', $this->file),
                $configException->getMessage(),
            );
        }
    }

    public function testLoadThrowsWhenTheCacheIsCorrupted(): void
    {
        $configCache = new ConfigCache(__DIR__ . '/fixtures/returns-int.php');

        try {
            $configCache->load();
            self::fail('A configuration cache that does not return an array must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                'The configuration cache "' . __DIR__ . '/fixtures/returns-int.php" '
                    . 'is corrupted: it does not return an array.',
                $configException->getMessage(),
            );
        }
    }

    public function testLoadThrowsWhenTheCacheReturnsNull(): void
    {
        $configCache = new ConfigCache(__DIR__ . '/fixtures/returns-null.php');

        try {
            $configCache->load();
            self::fail('A configuration cache that returns null must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                'The configuration cache "' . __DIR__ . '/fixtures/returns-null.php" '
                    . 'is corrupted: it does not return an array.',
                $configException->getMessage(),
            );
        }
    }

    public function testLoadThrowsWhenTheCacheIsNotValidPhp(): void
    {
        // A torn write -- `file_put_contents()` interrupted part-way -- leaves a
        // PHP file that does not even PARSE. `require` then raises a ParseError,
        // not the return-value corruption the other cases cover; the fail-closed
        // contract must still hold for it. The broken content is written at run
        // time rather than committed as a fixture so the syntax-lint gate (which
        // `php -l`s every committed `.php` file) never trips over it.
        file_put_contents($this->file, "<?php\n\ndeclare(strict_types=1);\n\nreturn array ( 'a' => 1,\n");

        $configCache = new ConfigCache($this->file);

        try {
            $configCache->load();
            self::fail('A configuration cache that is not valid PHP must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                'The configuration cache "' . $this->file . '" is corrupted: it is not valid PHP.',
                $configException->getMessage(),
            );
            self::assertSame(0, $configException->getCode());
            self::assertInstanceOf(ParseError::class, $configException->getPrevious());
        }
    }

    public function testDumpThrowsWhenTheCacheDirectoryIsMissing(): void
    {
        $orphan = $this->directory . '/missing/cache.php';
        $configCache = new ConfigCache($orphan);

        try {
            $configCache->dump(['key' => 'value']);
            self::fail('A dump into a missing directory must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                \sprintf('The configuration cache directory "%s" does not exist.', $this->directory . '/missing'),
                $configException->getMessage(),
            );
        }
    }

    public function testDumpThrowsWhenTheWriteFails(): void
    {
        // The cache target is the test directory itself: dirname() resolves to
        // the (existing) parent, so the pre-check passes. The atomic staging
        // write into the writable parent succeeds and the finalising rename
        // onto the directory target fails -- the unwritable-target shape now
        // lands on the finalisation arm, and the staging sibling never
        // survives its own failed rename. The custom error handler swallows
        // the engine's diagnostic for the failing rename; the branch under
        // test is the failure handling, not the diagnostic.
        set_error_handler(static fn (): bool => true);

        try {
            $configCache = new ConfigCache($this->directory);
            $configCache->dump(['key' => 'value']);
            self::fail('A failed configuration cache write must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                \sprintf('The configuration cache "%s" could not be finalised.', $this->directory),
                $configException->getMessage(),
            );
            $staging = glob(\dirname($this->directory) . '/' . basename($this->directory) . '.*.staging');
            self::assertIsArray($staging);
            self::assertSame(
                [],
                $staging,
                'the failed rename cleaned its own staging sibling',
            );
        } finally {
            restore_error_handler();
        }
    }

    public function testADumpThatRaisesMidWriteLeavesNoTornArtifact(): void
    {
        // The atomic contract: an artifact the previous dump wrote survives
        // a failed re-dump whole -- the staging sibling took the failure,
        // the reader-facing name never saw a partial byte.
        $file = $this->directory . '/cache-' . uniqid('', false) . '.php';
        $configCache = new ConfigCache($file);
        $configCache->dump(['previous' => 'whole']);

        set_error_handler(static fn (): bool => true);

        try {
            $unfinalisable = new ConfigCache($this->directory . '/subdirectory-that-does-not-exist/x.php');

            try {
                $unfinalisable->dump(['next' => 'torn']);
                self::fail('A dump into a missing directory must raise a ConfigException.');
            } catch (ConfigException $configException) {
                self::assertStringContainsString('does not exist.', $configException->getMessage());
            }
        } finally {
            restore_error_handler();
        }

        self::assertSame(['previous' => 'whole'], $configCache->load(), 'the previous artifact survived whole');

        unlink($file);
    }

    /**
     * Loads a cache this test just dumped. A freshly dumped cache must read
     * back, so the fail-closed `ConfigException` becomes a clean assertion
     * failure rather than a test error: `load()` chains the artifact's
     * `ParseError` as the exception's previous cause, and PHPUnit prints that
     * chain on an uncaught error -- output the mutation tooling then mistakes
     * for a mutated-source syntax error. The round trip is the assertion; the
     * fail-closed contract itself stays pinned by the corruption tests below.
     *
     * @return array<array-key, mixed>
     */
    private function loadDumpedCache(): array
    {
        try {
            return new ConfigCache($this->file)->load();
        } catch (ConfigException $configException) {
            self::fail(
                'A freshly dumped configuration cache must load back: '
                    . $configException->getMessage(),
            );
        }
    }
}

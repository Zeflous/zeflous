    public function testLoadThrowsWhenTheCacheIsNotValidPhp(): void
    {
        // A torn write -- `file_put_contents()` interrupted part-way --
        // leaves a PHP file that does not even PARSE. `require` then raises
        // a ParseError, not the shape corruption the other cases cover; the
        // fail-closed contract must still hold for it. The broken content
        // is written at run time rather than committed as a fixture so the
        // syntax-lint gate stays green.
        file_put_contents($this->file, '<?php return [');

        $routeTreeCache = new RouteTreeCache($this->file);

        try {
            $routeTreeCache->load();
            self::fail('A route tree cache that is not valid PHP must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                \sprintf('The route tree cache "%s" is corrupted: it is not valid PHP.', $this->file),
                $configException->getMessage(),
            );
            self::assertSame(0, $configException->getCode());
            self::assertInstanceOf(ParseError::class, $configException->getPrevious());
        }
    }


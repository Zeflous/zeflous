            $routeTreeCache->dump([['path' => 'users', 'method' => ['GET'], 'handler' => 'Users@show']]);
            self::fail('A dump of an invalid route entry must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                'The route path "users" must start with a slash.',
                $configException->getMessage(),
            );
        }
    }

    /**
     * The staging sibling's own name, observed through the engine's
     * diagnostic for the failing rename: the artifact's basename, the
     * writing process's own id, a twelve-hex-character entropy drawn from
     * `random_bytes`, and the `.staging` suffix -- a sibling no concurrent
     * writer can collide with. The rename onto the occupied directory
     * fails, the diagnostic carries the whole staging path, and the failed
     * dump still cleans its own sibling. (The same contract the
     * configuration cache's staging name keeps -- the two must stay
     * spellable the same way, and this battery pins this one against
     * every rearrangement of its composition.).
     */
    public function testTheStagingSiblingCarriesTheBasenameThePidAndTheEntropy(): void
    {
        $occupied = $this->directory . '/occupied';
        mkdir($occupied);
        file_put_contents($occupied . '/sentinel', 'x');

        $diagnostics = [];
        set_error_handler(static function (int $severity, string $message) use (&$diagnostics): bool {
            $diagnostics[] = $message;

            return true;
        });

        try {
            $routeTreeCache = new RouteTreeCache($occupied);

            try {
                $routeTreeCache->dump($this->table());
                self::fail('A dump onto an occupied directory target must raise a ConfigException.');
            } catch (ConfigException $configException) {
                self::assertSame(
                    \sprintf('The route tree cache "%s" could not be finalised.', $occupied),
                    $configException->getMessage(),
                );
            }
        } finally {
            restore_error_handler();
        }

        $renames = array_values(array_filter(
            $diagnostics,
            static fn (string $message): bool => str_starts_with($message, 'rename('),
        ));
        self::assertCount(1, $renames, 'exactly one rename diagnostic carries the staging path');
        self::assertMatchesRegularExpression(
            '/^rename\(' . preg_quote($occupied, '/') . '\.' . preg_quote((string) getmypid(), '/')
                . '-[0-9a-f]{12}\.staging,/',
            $renames[0],
            'the staging sibling is the basename, the pid, the entropy and the suffix',
        );

        $staging = glob($occupied . '.*.staging');
        self::assertIsArray($staging);
        self::assertSame([], $staging, 'the failed rename cleaned its own staging sibling');

        if (is_file($occupied . '/sentinel')) {
            unlink($occupied . '/sentinel');
        }

        rmdir($occupied);
    }

    /**
     * Dumps the mixed table, then rewrites the artifact with the mutation
     * applied to its decoded array -- surgical corruption of an otherwise
     * valid, parseable artifact.
     *
     * @param callable(array<array-key, mixed>): array<array-key, mixed> $mutator
     */
    private function corrupt(callable $mutator): void
    {
        new RouteTreeCache($this->file)->dump($this->table());

        $artifact = require $this->file;
        \assert(\is_array($artifact));

        file_put_contents($this->file, '<?php return ' . var_export($mutator($artifact), true) . ";\n");
    }

    /**
     * Rewrites one entry of the dumped artifact's route table.
     *
     * @param callable(array<array-key, mixed>): array<array-key, mixed> $mutator
     */
    private function corruptRoute(int $index, callable $mutator): void
    {
        $this->corrupt(static function (array $artifact) use ($index, $mutator): array {
            $routes = $artifact['routes'];
            \assert(\is_array($routes));

            $entry = $routes[$index];
            \assert(\is_array($entry));

            $routes[$index] = $mutator($entry);
            $artifact['routes'] = $routes;

            return $artifact;
        });
    }

    /**
     * Rewrites the dumped graph's "/" node -- the root's first static
     * child, the node every node-level corruption case below targets.
     *
     * @param callable(array<array-key, mixed>): array<array-key, mixed> $mutator
     */
    private function corruptSlashNode(callable $mutator): void
    {
        $this->corrupt(static function (array $artifact) use ($mutator): array {
            $root = $artifact['root'];
            \assert(\is_array($root));

            $static = $root['static'];
            \assert(\is_array($static));

            $slashNode = $static[0];
            \assert(\is_array($slashNode));

            $static[0] = $mutator($slashNode);
            $root['static'] = $static;
            $artifact['root'] = $root;

            return $artifact;
        });
    }

    /**
     * Asserts that loading the corrupted artifact fails closed with the
     * corruption reason in the message.
     */
    private function assertLoadIsCorrupted(string $reason): void
    {
        $routeTreeCache = new RouteTreeCache($this->file);

        try {
            $routeTreeCache->load();
            self::fail('The corrupted route tree cache must raise a ConfigException.');
        } catch (ConfigException $configException) {
            self::assertSame(
                \sprintf('The route tree cache "%s" is corrupted: %s', $this->file, $reason),
                $configException->getMessage(),
            );
        }
    }

    /**
     * Asserts the two trees answer every request in the battery with the
     * same outcome -- the equivalence pin that keeps the cache's dump/load
     * pair honest against `RadixTree::compile()`.
     */
    private function assertTreesAnswerAlike(RadixTree $first, RadixTree $second): void
    {
        $requests = [
            ['GET', '/', null, null, null],
            ['GET', '/boot', null, null, null],
            ['HEAD', '/foot', null, null, null],
            ['GET', '/users', null, null, null],
            ['GET', '/users/42', null, null, null],
            ['GET', '/users/abc', null, null, null],
            ['GET', '/users/42/posts/hello-world', null, null, null],
            ['GET', '/about', null, null, null],
            ['GET', '/dashboard', 'acme.example.com', null, null],
            ['GET', '/dashboard', 'other.example.org', null, null],
            ['GET', '/shop', 'api.example.com', null, null],
            ['GET', '/shop', 'a.b.example.com', null, null],
            ['GET', '/shop', null, null, null],
            ['GET', '/admin', 'admin.example.com', null, null],
            ['GET', '/admin', 'elsewhere.example.org', null, null],
            ['GET', '/status', null, null, 'v1'],
            ['GET', '/status', null, null, 'v2'],
            ['GET', '/status', null, null, null],
            ['GET', '/report', null, 'application/json', null],
            ['GET', '/report', null, 'text/html', null],
            ['PUT', '/things/7', null, null, null],
            ['GET', '/things/7', null, null, null],
            ['POST', '/secure', null, null, null],
            ['GET', '/café/日本語', null, null, null],
            ['GET', '/nope', null, null, null],
        ];

        foreach ($requests as [$method, $path, $host, $accept, $version]) {
            $this->assertOutcomesEqual(
                $first->match($method, $path, $host, $accept, $version),
                $second->match($method, $path, $host, $accept, $version),
                $method . ' ' . $path,
            );
        }
    }

    /**
     * Asserts two match outcomes are the same answer: the same shape, the
     * same parameters, the same route, the same allowed methods and the
     * same acceptable media types.
     */
    private function assertOutcomesEqual(MatchResult $first, MatchResult $second, string $request): void
    {
        $context = 'The request ' . $request . ' must answer alike.';

        self::assertSame($first->isFound(), $second->isFound(), $context);
        self::assertSame($first->isMethodNotAllowed(), $second->isMethodNotAllowed(), $context);
        self::assertSame($first->isNotAcceptable(), $second->isNotAcceptable(), $context);

        if ($first->isMethodNotAllowed()) {
            self::assertSame($first->allowedMethods(), $second->allowedMethods(), $context);
        }

        if ($first->isNotAcceptable()) {
            self::assertSame($first->acceptableMediaTypes(), $second->acceptableMediaTypes(), $context);
        }

        if (!$first->isFound()) {
            return;
        }

        self::assertSame($first->parameters(), $second->parameters(), $context);
        self::assertSame($first->route()->name(), $second->route()->name(), $context);
        self::assertSame($first->route()->handler(), $second->route()->handler(), $context);
        self::assertSame($first->route()->host(), $second->route()->host(), $context);
        self::assertSame($first->route()->version(), $second->route()->version(), $context);
        self::assertSame($first->route()->middleware(), $second->route()->middleware(), $context);
        self::assertSame($first->route()->meta(), $second->route()->meta(), $context);
    }


    public function testRoundTripsSiblingStaticTextWhoseFirstBytesCollide(): void
    {
        // "ähnlich" and "ånga" open with distinct letters whose UTF-8
        // encodings share the leading byte 0xC3: the rehydration must key
        // the siblings by character (the engine's own vocabulary, see
        // StaticRunInserter), so both stay reachable -- a byte-keyed
        // rehydration would judge them duplicates and refuse the artifact.
        $routes = [
            ['path' => '/ähnlich', 'method' => ['GET'], 'handler' => 'Similar@show'],
            ['path' => '/ånga', 'method' => ['GET'], 'handler' => 'Steam@show'],
        ];

        $routeTreeCache = new RouteTreeCache($this->file);
        $routeTreeCache->dump($routes);

        $loadedTree = $routeTreeCache->load();
        $compiledTree = RadixTree::compile($routes);

        self::assertSame('Similar@show', $loadedTree->match('GET', '/ähnlich')->route()->handler());
        self::assertSame('Steam@show', $loadedTree->match('GET', '/ånga')->route()->handler());
        self::assertSame(
            $compiledTree->match('GET', '/ähnlich')->route()->handler(),
            $loadedTree->match('GET', '/ähnlich')->route()->handler(),
        );
        self::assertFalse($loadedTree->match('GET', '/ähnlic')->isFound());
    }

    public function testRoundTripsTheNameIndexAndTheUrlGenerator(): void
    {
        $routeTreeCache = new RouteTreeCache($this->file);
        $routeTreeCache->dump($this->table());

        $loadedTree = $routeTreeCache->load();
        $compiledTree = RadixTree::compile($this->table());

        self::assertSame(
            $compiledTree->route('users.show')->handler(),
            $loadedTree->route('users.show')->handler(),
        );
        self::assertSame(
            $compiledTree->route('tenant.dashboard')->host(),
            $loadedTree->route('tenant.dashboard')->host(),
        );
        self::assertSame(
            $compiledTree->route('shop')->host(),
            $loadedTree->route('shop')->host(),
        );
        self::assertSame(
            '*.example.com',
            $loadedTree->route('shop')->host(),
        );
        self::assertSame(
            new RouteUrlGenerator($compiledTree)->generate('users.show', ['id' => '42']),
            new RouteUrlGenerator($loadedTree)->generate('users.show', ['id' => '42']),
        );
        self::assertSame(
            new RouteUrlGenerator($compiledTree)->generate('unicode', []),
            new RouteUrlGenerator($loadedTree)->generate('unicode', []),
        );
        self::assertSame(
            '/users/42',
            new RouteUrlGenerator($compiledTree)->generate('users.show', ['id' => '42']),
        );
        self::assertSame(
            new RouteUrlGenerator($compiledTree)->generateAbsolute('tenant.dashboard', ['tenant' => 'acme'], 'https'),
            new RouteUrlGenerator($loadedTree)->generateAbsolute('tenant.dashboard', ['tenant' => 'acme'], 'https'),
        );

        try {
            $loadedTree->route('never-registered');
            self::fail('An unknown route name must fail closed on the loaded tree as well.');
        } catch (ConfigException $configException) {
            self::assertSame(
                'The route name "never-registered" is not registered.',
                $configException->getMessage(),
            );
        }
    }

